#!/usr/bin/env node
// Bounded acceptance benchmark, exclusively on the checkout-owned kind cluster.
// Source the selected cluster sdk.env first. Results contain no credentials.
import { spawn } from "node:child_process";
import { runCommand } from "./bounded-process.mjs";
import { createServer } from "node:net";
import http from "node:http";
import { randomUUID } from "node:crypto";
import { mkdir, writeFile, cp, access } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { init } from "../sdk/src/init.mjs";
import { build } from "../sdk/src/build.mjs";
import { loadConfig } from "../sdk/src/config.mjs";
import { apiClient, deploy } from "../sdk/src/api.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
process.chdir(root);
const cluster = process.env.HIBANA_CLUSTER || "hibana";
if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(cluster)) throw new Error("Invalid HIBANA_CLUSTER");
const state = resolve(cluster === "hibana-dev" ? ".local/kubernetes" : `.local/kubernetes-${cluster}`);
const kube = ["--kubeconfig", resolve(state, "kubeconfig"), "--context", `kind-${cluster}`, "-n", "hibana"];
const project = resolve(".local/scale-test/scale-http");
const sleep = ms => new Promise(done => setTimeout(done, ms));
const forwards = [];
const agent = new http.Agent({keepAlive: true, maxSockets: 128});
const mode = process.argv[2] || "--regression";
if (!["--regression", "--capacity", "--hpa", "--soak"].includes(mode)) throw new Error("Usage: k8s-local-scale.mjs [--regression|--capacity|--hpa|--soak]");
let tenantId, adminUrl, initialReplicas, ownsHpa = false;

async function command(args, options = {}) {
  return runCommand("kubectl", [...kube, ...args], {
    timeoutMs: ["rollout", "wait"].includes(args[0]) ? 320000 : 30000, ...options,
  });
}
async function forward(pod, target) {
  const socket = createServer();
  await new Promise(done => socket.listen(0, "127.0.0.1", done));
  const port = socket.address().port;
  await new Promise(done => socket.close(done));
  const child = spawn("kubectl", [...kube, "port-forward", "--address", "127.0.0.1", `pod/${pod}`, `${port}:${target}`]);
  forwards.push(child);
  await new Promise((done, reject) => {
    const timeout = setTimeout(() => reject(new Error("port-forward startup timeout")), 10000);
    child.stdout.on("data", chunk => { if (String(chunk).includes("Forwarding from")) { clearTimeout(timeout); done(); } });
    child.stderr.resume();
    child.on("error", reject);
    child.on("exit", () => { clearTimeout(timeout); reject(new Error("port-forward exited")); });
  });
  return `http://127.0.0.1:${port}`;
}
async function admin(path, body, method = "PUT") {
  const response = await fetch(adminUrl + path, { method, headers: { "Authorization": `Bearer ${process.env.BOOTSTRAP_ADMIN_TOKEN}`, "Content-Type": "application/json" }, body: JSON.stringify(body), signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`admin request failed: ${response.status}`);
  return response.json();
}
async function database(options) {
  // Tenant IDs are generated by the server, but validate before embedding SQL.
  if (!/^ten_[a-f0-9]{32}$/.test(tenantId)) throw new Error("Unexpected tenant ID");
  const query = `SELECT json_build_object('pending',count(*) FILTER(WHERE status='pending'),'running',count(*) FILTER(WHERE status='running'),'rejected',count(*) FILTER(WHERE error->>'code'='dispatch_not_started'),'total',count(*),'connections',(SELECT count(*) FROM pg_stat_activity),'active_connections',(SELECT count(*) FROM pg_stat_activity WHERE state='active')) FROM executions WHERE tenant_id='${tenantId}'`;
  return JSON.parse(await command(["exec", "deployment/hibana-postgres", "--", "psql", "-U", "hibana_admin", "-d", "hibana", "-Atc", query], options));
}
function get(url, host) {
  return new Promise((done, reject) => {
    // Node fetch can discard Host overrides; use HTTP explicitly for virtual hosts.
    const request = http.get(url, {agent, headers: {Host: host}}, response => {
      let body = "";
      response.on("data", chunk => body += chunk);
      response.on("error", reject);
      response.on("end", () => done({status: String(response.statusCode), body, marker: response.headers["x-hibana-worker-rejected"]}));
    });
    const deadline = setTimeout(() => request.destroy(new Error("request timeout")), 60000);
    request.on("close", () => clearTimeout(deadline));
    request.on("error", reject);
  });
}
async function measure(urls, host, label, replicas, count, concurrency, path) {
  let next = 0;
  const records = [], dbSamples = [];
  let sampling = true;
  let sampleError;
  const sampler = (async () => { while (sampling) { dbSamples.push(await database()); await sleep(500); } })().catch(error => { sampleError = error; });
  const start = performance.now();
  await Promise.all(Array.from({length: concurrency}, async () => {
    while (next < count) {
      const index = next++, began = performance.now();
      let status = "transport", valid = false;
      try {
        const response = await get(urls[index % urls.length] + path, host);
        status = response.status;
        valid = status === "200" && response.body === "hibana-scale-ok";
        if (response.marker) throw new Error("internal marker leaked");
      } catch { status = "transport"; valid = false; }
      records.push({status, valid, ms: performance.now() - began});
    }
  }));
  const seconds = (performance.now() - start) / 1000;
  sampling = false; await sampler;
  if (sampleError) throw sampleError;
  const latencies = records.map(r => r.ms).sort((a,b) => a-b);
  const good = records.filter(r => r.valid);
  const successLatencies = good.map(r => r.ms).sort((a,b) => a-b);
  const percentile = (values, p) => values.length ? Math.round(values[Math.ceil(values.length * p) - 1] * 100) / 100 : null;
  const result = {label, replicas, count, concurrency, seconds: +seconds.toFixed(2), success_rps: +(good.length / seconds).toFixed(2), statuses: {}, p95_ms: percentile(latencies, .95), p99_ms: percentile(latencies, .99), success_p95_ms: percentile(successLatencies, .95), max_db_connections: Math.max(...dbSamples.map(s => s.connections)), max_active_db_connections: Math.max(...dbSamples.map(s => s.active_connections)), after: await database()};
  for (const record of records) result.statuses[record.status] = (result.statuses[record.status] || 0) + 1;
  console.log(JSON.stringify(result));
  if (result.after.pending || result.after.running) throw new Error("Reservations left after completed load");
  return result;
}
async function main() {
  await access(resolve(state, "kubeconfig"));
  if (!process.env.BOOTSTRAP_ADMIN_TOKEN) throw new Error("Source the selected cluster sdk.env first");
  const deployment = JSON.parse(await command(["get", "deployment/hibana-worker", "-o", "json"]));
  initialReplicas = deployment.spec.replicas;
  const hpas = JSON.parse(await command(["get", "hpa", "-o", "json"]));
  if (hpas.items.some(h => h.spec.scaleTargetRef.name === "hibana-worker")) throw new Error("Remove Worker HPA before manual scaling measurements");
  const cps = JSON.parse(await command(["get", "pods", "-l", "app.kubernetes.io/name=hibana-control-plane", "-o", "json"])).items.filter(p => p.status.conditions.some(c => c.type === "Ready" && c.status === "True"));
  adminUrl = await forward(cps[0].metadata.name, 8080);
  // Explicitly distribute over both CP Pods: one Service port-forward pins one Pod.
  const urls = await Promise.all(cps.map(p => forward(p.metadata.name, 8083)));
  const slug = `scale-${randomUUID().slice(0, 8)}`;
  const password = randomUUID() + randomUUID();
  const created = await admin("/admin/tenants", {slug, name: "Isolated scale acceptance", admin_email: "scale@example.invalid", admin_password: password}, "POST");
  tenantId = created.tenant_id;
  await admin(`/admin/tenants/${tenantId}/quotas`, {invoke_rate_per_sec: 500, invoke_burst: 1000, max_concurrent_executions: 200});
  await mkdir(resolve(project, ".."), {recursive: true});
  try { await access(resolve(project, "hibana.json")); } catch { await init(project, {template: "rust"}); }
  await cp("scripts/fixtures/scale-http.rs", resolve(project, "src/lib.rs"));
  Object.assign(process.env, {HIBANA_URL: adminUrl, HIBANA_TENANT: slug, HIBANA_EMAIL: "scale@example.invalid", HIBANA_PASSWORD: password});
  delete process.env.HIBANA_TOKEN;
  const api = await apiClient(project); await api.login();
  const config = await loadConfig(resolve(project, "hibana.json"));
  const artifact = await build(config);
  await deploy(api, config, artifact, `0.0.0-scale.${Date.now()}`);
  await deploy(api, {...config, name: "memory-scale", resources: {...config.resources, max_memory_bytes: 1024 * 1024 * 1024}}, artifact, `0.0.0-scale.${Date.now()}`);
  const host = `scale-http.${slug}.hibana.local`, results = [];
  const probe = await get(urls[0] + "/fast", host);
  if (probe.status !== "200" || probe.body !== "hibana-scale-ok") throw new Error(`Fixture not healthy: HTTP ${probe.status}`);
  if (mode === "--soak") {
    const {soak} = await import("./soak.mjs");
    await soak({urls, slug, project, command, database, replicas: initialReplicas});
    return;
  }
  if (mode === "--hpa") {
    await command(["get", "--raw", "/apis/metrics.k8s.io/v1beta1/namespaces/hibana/pods"]);
    await command(["apply", "-k", "deploy/kubernetes/autoscaling"]);
    ownsHpa = true;
    const observations = [];
    let loading = true;
    const load = Promise.all(Array.from({length: 12}, async () => {
      while (loading) {
        const response = await get(urls[Math.floor(Math.random() * urls.length)] + "/cpu", host);
        if (response.status !== "200" && response.status !== "503") throw new Error(`HPA load returned ${response.status}`);
      }
    })).catch(error => { loading = false; return error; });
    try {
      for (let elapsed = 0; elapsed < 240 && loading; elapsed += 10) {
        await sleep(10000);
        const hpa = JSON.parse(await command(["get", "hpa/hibana-worker", "-o", "json"]));
        const workers = JSON.parse(await command(["get", "deployment/hibana-worker", "-o", "json"]));
        const sample = {seconds: elapsed + 10, current: hpa.status.currentReplicas, desired: hpa.status.desiredReplicas, ready: workers.status.readyReplicas, metrics: hpa.status.currentMetrics};
        observations.push(sample); console.log(JSON.stringify(sample));
        if (sample.ready >= 4 && sample.current >= 4) break;
      }
    } finally { loading = false; }
    const error = await load; if (error instanceof Error) throw error;
    await writeFile(".local/scale-test/hpa.json", JSON.stringify(observations, null, 2) + "\n");
    if (!observations.some(s => s.ready >= 4 && s.current >= 4)) throw new Error("HPA did not reach four ready Workers within 240 seconds");
    console.log("PASS: CPU HPA scaled Worker deployment automatically; scale-down stabilization not timed in this test");
    return;
  }
  for (const replicas of [2, 4, 8]) {
    await command(["scale", "deployment/hibana-worker", `--replicas=${replicas}`]);
    if (mode === "--regression") await command(["rollout", "restart", "deployment/hibana-worker"]);
    await command(["rollout", "status", "deployment/hibana-worker", "--timeout=300s"]);
    // Let terminating old Pods leave EndpointSlices before measuring fresh caches.
    for (let wait = 0; ; wait++) {
      const pods = JSON.parse(await command(["get", "pods", "-l", "app.kubernetes.io/name=hibana-worker", "-o", "json"])).items;
      if (pods.length === replicas && pods.every(p => !p.metadata.deletionTimestamp)) break;
      if (wait > 90) throw new Error("Old Worker Pods did not drain");
      await sleep(1000);
    }
    await sleep(3000);
    if (mode === "--capacity") {
      for (let warm = 0; warm < 32; warm++) {
        const response = await get(urls[warm % urls.length] + "/fast", host);
        if (response.status !== "200") throw new Error("Warmup failed");
      }
      const sample = await measure(urls, host, "capacity", replicas, 960, replicas * 6, "/hold");
      results.push(sample);
      if (sample.statuses["200"] !== 960) throw new Error("Capacity run rejected requests");
      continue;
    }
    results.push(await measure(urls, host, "cold", replicas, 32, 8, "/fast"));
    results.push(await measure(urls, host, "warm", replicas, 240, 12, "/hold"));
    results.push(await measure(urls, host, "overload", replicas, 240, 96, "/hold"));
    results.push(await measure(urls, `memory-scale.${slug}.hibana.local`, "memory-pressure", replicas, 80, 32, "/hold"));
    const recovery = await measure(urls, host, "recovery", replicas, 24, 4, "/fast");
    if (recovery.statuses["200"] !== 24) throw new Error("Admission did not recover after overload");
    results.push(recovery);
    const before = await database();
    const forged = await measure(urls, host, "guest-503", replicas, 4, 1, "/guest-error");
    if (forged.statuses["503"] !== 4 || forged.after.total - before.total !== 4 || forged.after.rejected !== before.rejected) throw new Error("Guest 503 was retried or cancelled");
    results.push(forged);
  }
  const output = `.local/scale-test/${mode === "--capacity" ? "capacity" : "results"}.json`;
  await writeFile(output, JSON.stringify({date: new Date().toISOString(), topology: "Docker Desktop; two logical Worker nodes; two CP Pods via separate port-forwards; closed-loop client", results}, null, 2) + "\n");
  console.log(`PASS: ${mode}; results in ${output}`);
}
try { await main(); }
catch (error) { console.error(error.message); process.exitCode = 1; }
finally {
  if (ownsHpa) await command(["delete", "hpa/hibana-worker", "--ignore-not-found"]).catch(() => { console.error("HPA cleanup failed"); process.exitCode = 1; });
  if (tenantId && adminUrl) await admin(`/admin/tenants/${tenantId}/status`, {status: "suspended"}).catch(() => { console.error("Test tenant suspension failed"); process.exitCode = 1; });
  if (initialReplicas !== undefined) await command(["scale", "deployment/hibana-worker", `--replicas=${initialReplicas}`]).catch(() => { console.error("Restore replicas failed"); process.exitCode = 1; });
  for (const child of forwards) child.kill();
  agent.destroy();
}
